import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Route = { method: string; pattern: string; line: number; shape: "literal" | "regex" };

const source = readFileSync(join(import.meta.dir, "..", "src", "server.ts"), "utf8");
const lines = source.split("\n");

const routes: Route[] = [];
let methodHint = "";
let scanning = false;

for (let index = 0; index < lines.length; index++) {
  const line = lines[index];
  if (!scanning) {
    if (line.includes("async function handleApi")) scanning = true;
    continue;
  }

  const literal = /path === "(\/api\/[^"]+)"/.exec(line);
  const method = /request\.method === "([A-Z]+)"/.exec(line);
  const regexRoute = /= \/(.*)\/\.exec\(path\)/.exec(line);

  if (literal) methodHint = method ? method[1] : "";
  if (literal && method) {
    routes.push({ method: method[1], pattern: literal[1], line: index + 1, shape: "literal" });
  } else if (regexRoute) {
    const pattern = regexRoute[1];
    const span = lines.slice(index, index + 14).join("\n");
    const methods = [...span.matchAll(/request\.method === "([A-Z]+)"/g)].map((match) => match[1]);
    for (const found of methods.length ? methods : [methodHint || "GET"]) {
      routes.push({ method: found, pattern: `/${pattern}`, line: index + 1, shape: "regex" });
    }
  }
}

const deduped = routes.filter((route, index) =>
  routes.findIndex((other) => other.method === route.method && other.pattern === route.pattern) === index);

const rows = deduped
  .sort((a, b) => a.pattern.localeCompare(b.pattern) || a.method.localeCompare(b.method))
  .map((route) => `| ${route.method} | \`${route.pattern}\` | src/server.ts:${route.line} |`)
  .join("\n");

const nodes = deduped
  .map((route) => `  R${route.line}_${route.method}["${route.method} ${route.pattern}"]`)
  .join("\n");

const doc = `# Saber route table (generated)

Generated by \`bun scripts/generate-route-table.ts\` from \`src/server.ts\`.
Do not edit by hand. Once fix 1 (route descriptor array) lands, this reads the
descriptor table instead of scanning the router source.

Found ${deduped.length} routes.

| Method | Pattern | Source |
| --- | --- | --- |
${rows}

\`\`\`mermaid
flowchart TB
${nodes}
\`\`\`
`;

writeFileSync(join(import.meta.dir, "..", "docs", "architecture", "route-table.gen.md"), doc);
console.log(`wrote route-table.gen.md with ${deduped.length} routes`);
