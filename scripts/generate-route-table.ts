import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { dedupeRoutes, extractRoutes, type RouteSource } from "../src/server/routes/routeScan";

const routeModules = ["tasks", "terminals", "sessions", "projects", "roles", "environment"];

const sources: RouteSource[] = routeModules.map((name) => ({
  file: `src/server/routes/${name}.ts`,
  text: readFileSync(join(import.meta.dir, "..", "src", "server", "routes", `${name}.ts`), "utf8"),
}));

const routes = dedupeRoutes(extractRoutes(sources));
if (routes.length === 0) {
  throw new Error("No routes found in src/server/routes; the scanner no longer matches the router source.");
}

const rows = routes
  .sort((a, b) => a.pattern.localeCompare(b.pattern) || a.method.localeCompare(b.method))
  .map((route) => `| ${route.method} | \`${route.pattern}\` | ${route.source}:${route.line} |`)
  .join("\n");

const nodes = routes
  .map((route) => `  R${route.source.replace(/[^a-zA-Z0-9]/g, "_")}_${route.line}_${route.shape}["${route.method} ${route.pattern}"]`)
  .join("\n");

const doc = `# Saber route table (generated)

Generated by \`bun scripts/generate-route-table.ts\` from \`src/server/routes/*.ts\`.
Do not edit by hand. A \`*\` method means the route is matched by a path
pattern whose methods are decided inside the handler.

Found ${routes.length} routes.

| Method | Pattern | Source |
| --- | --- | --- |
${rows}

\`\`\`mermaid
flowchart TB
${nodes}
\`\`\`
`;

writeFileSync(join(import.meta.dir, "..", "docs", "architecture", "route-table.gen.md"), doc);
console.log(`wrote route-table.gen.md with ${routes.length} routes`);
