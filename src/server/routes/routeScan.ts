export type RouteShape = "literal" | "regex";

export type Route = {
  method: string;
  pattern: string;
  line: number;
  shape: RouteShape;
  source: string;
};

export type RouteSource = {
  file: string;
  text: string;
};

const METHOD_LINE = /request\.method === "([A-Z]+)"/;
const LITERAL_LINE = /path === "(\/api\/[^"]+)"/;
const REGEX_LINE = /const \w+ = \/(.*)\/\.exec\(path\)/;

export function extractRoutes(sources: RouteSource[]): Route[] {
  const routes: Route[] = [];
  for (const { file, text } of sources) {
    const lines = text.split("\n");
    for (let index = 0; index < lines.length; index++) {
      const line = lines[index];
      const literal = LITERAL_LINE.exec(line);
      const method = METHOD_LINE.exec(line);
      const regexRoute = REGEX_LINE.exec(line);

      if (literal && method) {
        routes.push({ method: method[1], pattern: literal[1], line: index + 1, shape: "literal", source: file });
      } else if (regexRoute) {
        routes.push({ method: "*", pattern: `/${regexRoute[1]}/`, line: index + 1, shape: "regex", source: file });
      }
    }
  }
  return routes;
}

export function dedupeRoutes(routes: Route[]): Route[] {
  return routes.filter((route, index) =>
    routes.findIndex((other) => other.method === route.method && other.pattern === route.pattern) === index);
}

export function renderRouteTable(input: Route[]): string {
  const routes = input
    .slice()
    .sort((a, b) => a.pattern.localeCompare(b.pattern) || a.method.localeCompare(b.method));
  const rows = routes
    .map((route) => `| ${route.method} | \`${route.pattern}\` | ${route.source}:${route.line} |`)
    .join("\n");
  const nodes = routes
    .map((route) => `  R${route.source.replace(/[^a-zA-Z0-9]/g, "_")}_${route.line}_${route.shape}["${route.method} ${route.pattern}"]`)
    .join("\n");

  return `# Saber route table (generated)

Generated by \`bun scripts/generate-route-table.ts\` from \`src/server/routes/*.ts\`.
Do not edit by hand. A \`*\` method means the route is matched by a path
pattern whose methods are decided inside the handler.

Found ${routes.length} routes.

| Method | Pattern | Source |
| --- | --- | --- |
${rows}

\`\`\`mermaid
flowchart TB
${nodes}
\`\`\`
`;
}
